"""Fraud check: FraudChecker interface + deterministic MockFraudChecker + MCP client."""
from __future__ import annotations

import base64
import json
import urllib.request
from pathlib import Path
from typing import Optional, Protocol

from core import config
from core.models import Bill, FraudResult

EDIT_TOOLS = ["photoshop", "gimp", "canva", "midjourney", "dall-e", "stable diffusion", "firefly"]
MOCK_LABEL = "Demo fraud check (mock)"


class FraudChecker(Protocol):
    def score(self, file_path: str) -> FraudResult: ...


def _file_metadata(file_path: str) -> tuple[list[str], bool]:
    """-> (software/producer strings, has_exif)."""
    p = Path(file_path)
    if p.suffix.lower() == ".pdf":
        try:
            import pymupdf
            meta = pymupdf.open(file_path).metadata or {}
            return [meta.get("producer") or "", meta.get("creator") or ""], False
        except Exception:
            return [], False
    try:
        from PIL import Image
        with Image.open(file_path) as im:
            exif = im.getexif()
            strings = [str(exif.get(305, ""))]          # 0x0131 Software
            strings.append(str(im.info.get("Software", "")))
            return strings, len(exif) > 0
    except Exception:
        return [], False


class MockFraudChecker:
    is_mock = True

    def __init__(self, source: Optional[str] = None):
        self.source = source

    def score(self, file_path: str) -> FraudResult:
        strings, has_exif = _file_metadata(file_path)
        joined = " ".join(strings).lower()
        for tool in EDIT_TOOLS:
            if tool in joined:
                return FraudResult(85, [f"Edited/generated by {tool}"], is_mock=True)
        if not has_exif and self.source == "scan" and Path(file_path).suffix.lower() != ".pdf":
            return FraudResult(20, ["No camera metadata"], is_mock=True)
        return FraudResult(10, [], is_mock=True)


class MCPFraudChecker:
    """Sends the file to FRAUD_MCP_URL as a JSON-RPC `tools/call` (tool `score_receipt`).
    Unverified against a specific server (PRD Section 17); any failure falls back to the mock."""
    is_mock = False

    def __init__(self, url: str, source: Optional[str] = None):
        self.url, self.source = url, source

    def score(self, file_path: str) -> FraudResult:
        try:
            payload = {
                "jsonrpc": "2.0", "id": 1, "method": "tools/call",
                "params": {"name": "score_receipt", "arguments": {
                    "filename": Path(file_path).name,
                    "file_base64": base64.b64encode(Path(file_path).read_bytes()).decode()}},
            }
            req = urllib.request.Request(self.url, data=json.dumps(payload).encode(),
                                         headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=15) as r:
                body = json.loads(r.read())
            result = body.get("result", body)
            if isinstance(result, dict) and "content" in result:      # MCP text content
                result = json.loads(result["content"][0]["text"])
            return FraudResult(int(result["score"]), list(result.get("signals", [])), is_mock=False)
        except Exception:
            res = MockFraudChecker(self.source).score(file_path)
            res.signals = res.signals + ["MCP unavailable - mock used"]
            return res


def get_checker(source: Optional[str] = None) -> FraudChecker:
    if config.FRAUD_MCP_URL:
        return MCPFraudChecker(config.FRAUD_MCP_URL, source)
    return MockFraudChecker(source)


def check_fraud(bill: Bill) -> FraudResult:
    if bill.source == "manual" or not bill.file_path:
        return FraudResult(0, ["Manual entry - no document"], is_mock=False)
    return get_checker(bill.source).score(bill.file_path)
