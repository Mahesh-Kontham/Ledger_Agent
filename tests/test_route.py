from core.models import Bill
from core.route import decide


def mk(**kw):
    base = dict(source="upload", mode="INDIVIDUAL", merchant_raw="Swiggy", bill_date="2026-11-10",
                total_amount=100.0, total_amount_inr=100.0, currency="INR", payment_mode="CARD",
                fraud_score=10, match_status="MATCHED", matched_transaction_id=1, variance_inr=0.0)
    base.update(kw)
    return Bill(**base)


def test_duplicate_first():
    s, r, _ = decide(mk(duplicate_of=12, missing_fields=["bill_date"], fraud_score=90), "INDIVIDUAL")
    assert s == "DUPLICATE" and r == ["Duplicate of bill #12"]


def test_missing_before_fraud():
    s, r, p = decide(mk(missing_fields=["bill_date", "total_amount"], fraud_score=90), "INDIVIDUAL")
    assert s == "MISSING_DATA" and p == "NORMAL" and r[0] == "Missing: bill_date, total_amount"


def test_individual_fraud_thresholds():
    assert decide(mk(fraud_score=85, fraud_signals=["Edited/generated by photoshop"]), "INDIVIDUAL")[:3:2] == ("NEEDS_REVIEW", "HIGH")
    s, r, _ = decide(mk(fraud_score=45), "INDIVIDUAL")
    assert s == "VERIFIED" and any("Fraud risk warning" in x for x in r)
    assert decide(mk(fraud_score=39), "INDIVIDUAL")[0] == "VERIFIED"


def test_business_fraud_thresholds():
    s, r, p = decide(mk(mode="BUSINESS", fraud_score=45), "BUSINESS")
    assert (s, p) == ("NEEDS_REVIEW", "NORMAL") and r[0] == "Fraud risk 45%"
    assert decide(mk(mode="BUSINESS", fraud_score=70), "BUSINESS")[2] == "HIGH"
    assert decide(mk(mode="BUSINESS", fraud_score=39), "BUSINESS")[0] == "VERIFIED"


def test_unexplained_variance_needs_review():
    s, r, p = decide(mk(match_status="VARIANCE_UNEXPLAINED", variance_reason="Unexplained gap of ₹18"), "INDIVIDUAL")
    assert s == "NEEDS_REVIEW" and p == "NORMAL" and "Unexplained gap of ₹18" in r[0]


def test_no_match_by_mode():
    s, r, _ = decide(mk(match_status="NO_MATCH", matched_transaction_id=None), "INDIVIDUAL")
    assert s == "VERIFIED" and "Single source - not bank-verified" in r
    s, r, _ = decide(mk(mode="BUSINESS", match_status="NO_MATCH", matched_transaction_id=None), "BUSINESS")
    assert s == "NEEDS_REVIEW" and r[0] == "No bank/card debit found"


def test_every_status_has_reason():
    for b, mode in [(mk(), "INDIVIDUAL"), (mk(fraud_score=0, match_status="MATCHED"), "BUSINESS")]:
        s, r, _ = decide(b, mode)
        assert r, s
