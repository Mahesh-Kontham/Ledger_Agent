def test_bill1_clean_matched(fresh_db):
    b = upload("bill1_swiggy.png")
    assert b.status == "VERIFIED" and b.match_status == "MATCHED"
    assert b.merchant_normalized == "Swiggy" and b.category == "Food"
    assert db.get_transaction(b.matched_transaction_id).matched_bill_id == b.id


def test_bill2_card_fee_and_three_way_note(fresh_db):
    b = upload("bill2_rapido.png", user_entered_amount=120)
    assert b.status == "VERIFIED"
    assert b.match_status == "VARIANCE_EXPLAINED"
    assert b.variance_reason == "Probable card fee - confirm"
    assert b.variance_inr == 5.0
    assert any("You entered ₹120; invoice shows ₹125; bank debited ₹130" in r for r in b.status_reasons)


def test_bill3_duplicate_same_file(fresh_db):
    first = upload("bill2_rapido.png", user_entered_amount=120)
    dup = upload("bill2_rapido.png")
    assert dup.status == "DUPLICATE" and dup.duplicate_of == first.id
