def test_unexplained_gap(fresh_db):
    b = Bill(source="manual", mode="INDIVIDUAL", total_amount=100.0, total_amount_inr=100.0,
             currency="INR", payment_mode="UPI")
    m = verify.classify_variance(b, 18.0)
    assert m.match_status == "VARIANCE_UNEXPLAINED" and m.variance_reason == "Unexplained gap of ₹18"


def test_fee_items_explain_variance(fresh_db):
    b = Bill(source="manual", mode="INDIVIDUAL", total_amount_inr=500.0, currency="INR", payment_mode="UPI",
             fee_items=[{"description": "Convenience fee", "amount": 20.0}])
    m = verify.classify_variance(b, 20.0)
    assert m.match_status == "VARIANCE_EXPLAINED" and m.variance_reason == "Fee on bill: Convenience fee"


def test_mandatory_business_gstin_rule():
    b = Bill(source="manual", mode="BUSINESS", merchant_raw="X", bill_date="2026-11-01", total_amount=100.0,
             currency="INR", payment_mode="CASH", invoice_number="1", tax_amount=18.0)
    assert verify.check_mandatory(b, "BUSINESS") == ["gstin"]
    assert verify.check_mandatory(b, "INDIVIDUAL") == []


def test_low_confidence_is_nulled():
    obj = {"merchant": {"value": "Swiggy", "confidence": 0.99},
           "total_amount": {"value": 456, "confidence": 0.5},
           "bill_date": {"value": "10/11/2026", "confidence": 0.99}}
    ext = extract.postprocess(obj)
    assert ext.values["merchant"] == "Swiggy"
    assert ext.values["total_amount"] is None and "total_amount" in ext.low_confidence_fields
    assert ext.values["bill_date"] is None


def test_bad_json_retries_then_fails(fresh_db, tmp_path):
    calls = []

    def bad_llm(img, media):
        calls.append(1)
        return "not json"
    from core.config import SAMPLE_DIR
    from core.models import RawBill
    raw = RawBill(source="upload", file_path=str(SAMPLE_DIR / "bill1_swiggy.png"), filename="bill1_swiggy.png")
    ext = extract.extract_fields(raw, llm=bad_llm)
    assert len(calls) == 2 and ext.error and all(v is None for v in ext.values.values())


